#!/usr/bin/env python3
import os
import sys

# Read registry and generate types.go
registry_file = "lib/sensors/registry.txt"
output_file = "lib/sensors/types.go"

if not os.path.exists(registry_file):
    print(f"ERROR: {registry_file} not found")
    sys.exit(1)

sensors = []
with open(registry_file) as f:
    for line in f:
        parts = line.strip().split('\t')
        if len(parts) >= 2:
            sensors.append(parts[0].split(':')[0])

# Generate types.go
with open(output_file, 'w') as f:
    f.write("// Package sensors holds sensor type definitions — generated by sensors.py.\n")
    f.write("package sensors\n\n")
    f.write("// SensorTypes returns the registered sensor types.\n")
    f.write("func SensorTypes() []string {\n")
    f.write("\treturn []string{\n")
    for sensor in sensors:
        f.write(f'\t\t"{sensor}",\n')
    f.write("\t}\n}\n")

print(f"Generated {output_file} with {len(sensors)} sensor types")
