def _preflight(targets: List[Dict[str, Any]]) -> Dict[str, Dict[str, Any]]:
    """
    Verify -- BEFORE any money is spent -- that the derived population is
    exactly the verified census, and that every target's context is actually
    resolvable (fail loud, never silently fall back). Returns per-moment_id
    prep: judged_from, injected flag, and pre-resolved context blocks.
    """
    if len(targets) != EXPECTED_TARGET_COUNT:
        raise ValueError(
            f"expected exactly {EXPECTED_TARGET_COUNT} distinct target moments, "
            f"found {len(targets)} -- refusing to run against an unexpected population"
        )

    field_counts: Counter = Counter()
    for target in targets:
        field_counts.update(target["ask_fields"])
    if dict(field_counts) != EXPECTED_FIELD_COUNTS:
        raise ValueError(
            f"per-field census mismatch: expected {EXPECTED_FIELD_COUNTS}, "
            f"derived {dict(field_counts)}"
        )

    recheck_ids = {
        t["moment"]["moment_id"] for t in targets if t["needs_existence_recheck"]
    }
    if recheck_ids != EXPECTED_RECHECK_IDS:
        raise ValueError(
            f"memory_existed-null census mismatch: expected {sorted(EXPECTED_RECHECK_IDS)}, "
            f"derived {sorted(recheck_ids)}"
        )

    events_by_basename = _load_events_by_basename(EVENTS_PATH)
    fork_context_cache: Dict[str, Dict[str, Any]] = {}
    prep: Dict[str, Dict[str, Any]] = {}

    for target in targets:
        moment = target["moment"]
        moment_id = moment["moment_id"]
        finding = moment.get("finding_side") or {}
        transcript_path = moment["transcript_path"]
        basename = os.path.basename(transcript_path)
        transcript_exists = os.path.exists(transcript_path)
        injected = finding.get("search_ran") == "injected"

        if injected:
            judged_from = "fork-inherited"
            if not transcript_exists:
                raise ValueError(f"{moment_id}: fork target with missing transcript")
        elif transcript_exists:
            judged_from = "transcript"
        else:
            judged_from = "chunks"
            _find_chunk_file(transcript_path)  # fail loud now, not mid-run

        extra_blocks: List[Tuple[str, str]] = []

        if injected and finding.get("surfaced") is True:
            if transcript_path not in fork_context_cache:
                fork_context_cache[transcript_path] = _resolve_fork_parent_context(transcript_path)
            fork_context = fork_context_cache[transcript_path]
            if not fork_context["available"] or not fork_context["recalled_notes"]:
                raise ValueError(
                    f"{moment_id}: fork parent context unresolvable "
                    f"(available={fork_context['available']}, reason={fork_context['reason']!r})"
                )
            extra_blocks.append(
                (
                    "MEMORY CONTENT THE AGENT INHERITED (recalled in the parent conversation "
                    "before the fork point; this fork inherited the parent's full prior "
                    "conversation, so this content IS what was 'surfaced' for it)",
                    _fork_inherited_block(fork_context),
                )
            )
        elif not injected and (
            finding.get("surfaced") is True or "search_targeted_right_thing" in target["ask_fields"]
        ):
            if basename not in events_by_basename:
                raise KeyError(f"{moment_id}: no transcript-events.jsonl record for {basename}")
            extra_blocks.append(
                (
                    "WHAT THIS AGENT'S OWN RECALL ACTUALLY DID (query phrases + matched notes, "
                    "each shown with its current vault content)",
                    _recall_content_block(events_by_basename[basename], moment["location"]),
                )
            )

        if any(field.startswith("note_") for field in target["ask_fields"]):
            if basename not in events_by_basename:
                raise KeyError(f"{moment_id}: no transcript-events.jsonl record for {basename}")
            extra_blocks.append(
                (
                    "ENGRAM WRITE COMMANDS THIS SESSION RAN (learn/amend, from transcript "
                    "events; these contain the actually-written note content under judgment)",
                    _write_commands_block(events_by_basename[basename]),
                )
            )

        prep[moment_id] = {
            "judged_from": judged_from,
            "injected": injected,
            "extra_blocks": extra_blocks,
        }
        print(
            f"preflight: {moment_id} judged_from={judged_from} "
            f"fields={target['ask_fields']} recheck={target['needs_existence_recheck']}",
            flush=True,
        )

    return prep


