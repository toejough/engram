def _load_events_by_basename(path: Path) -> Dict[str, Dict[str, Any]]:
    """transcript-events.jsonl records keyed by transcript basename. Fail loud on collisions."""
    by_basename: Dict[str, Dict[str, Any]] = {}
    with open(path, "r") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            rec = json.loads(line)
            basename = os.path.basename(rec["transcript_path"])
            if basename in by_basename:
                raise ValueError(f"duplicate transcript basename in {path}: {basename}")
            by_basename[basename] = rec
    return by_basename


def _last_recall_call(events_record: Dict[str, Any], location: int) -> Dict[str, Any]:
    """The recall_calls entry at-or-before the moment's location. Fail loud if none."""
    qualifying = [
        rc for rc in events_record.get("recall_calls", []) if rc.get("location", 0) <= location
    ]
    if not qualifying:
        raise ValueError(
            f"no recall_call at-or-before location {location} in "
            f"{events_record['transcript_path']}"
        )
    return max(qualifying, key=lambda rc: rc.get("location", 0))


def _recall_content_block(events_record: Dict[str, Any], location: int) -> str:
    """
    What a non-injected moment's recall actually did: the query phrases plus
    each matched note's path and CURRENT vault content (best-effort -- a
    renamed/superseded/deleted note is honestly marked, never silently
    dropped). Zero matched items is stated honestly (the search-targeting
    question is still answerable from the phrases).
    """
    last_recall = _last_recall_call(events_record, location)
    lines: List[str] = []
    phrases = last_recall.get("query_phrases") or []
    if phrases:
        lines.append("Query phrases the recall ran:")
        lines.extend(f"  - {phrase}" for phrase in phrases)
    skill_args = last_recall.get("skill_args")
    if skill_args:
        lines.append(f"Recall skill args: {skill_args}")
    matched = last_recall.get("matched_items", [])
    if not matched:
        lines.append("Matched items: NONE (the search returned no matches).")
        return "\n".join(lines)
    lines.append("")
    for item in matched:
        note_path = item.get("path")
        if not note_path:
            continue
        try:
            with open(VAULT_DIR / note_path, "r") as f:
                content = f.read()
        except (IOError, OSError):
            content = NOTE_GONE
        lines.append(f"--- {note_path} (rank {item.get('rank')}, score {item.get('score')}) ---")
        lines.append(content)
        lines.append("")
    return "\n".join(lines)


def _fork_inherited_block(fork_context: Dict[str, Any]) -> str:
    """Format _resolve_fork_parent_context's recalled_notes as one content block."""
    sections = []
    for note in fork_context["recalled_notes"]:
        sections.append(f"--- {note['path']} ---\n{note['content']}")
    return "\n\n".join(sections)


def _write_commands_block(events_record: Dict[str, Any]) -> str:
    """
    Every engram learn/amend command this session ran (from transcript-
    events.jsonl), in location order -- the actually-written note content the
    population-d questions judge.
    """
    commands = [
        cmd
        for cmd in events_record.get("engram_commands", [])
        if cmd.get("command") in ("learn", "amend")
    ]
    commands.sort(key=lambda cmd: cmd.get("location", 0))
    if not commands:
        return "(no engram learn/amend commands recorded for this session)"
    sections = []
    for cmd in commands:
        sections.append(
            f"--- line {cmd.get('location')} ({cmd.get('command')}) ---\n"
            f"{cmd.get('full_command_text', '')}"
        )
    return "\n\n".join(sections)


def _find_covering_window(windows: List[Dict[str, Any]], location: int) -> Optional[Dict[str, Any]]:
    """Find the single window whose location_start <= location <= location_end."""
    for w in windows:
        if w["location_start"] <= location <= w["location_end"]:
            return w
    return None


def _numbered_window_text(window: Dict[str, Any]) -> str:
    """
    Window text with absolute line numbers -- the SAME numbering scheme
    judge_moment uses: each line prefixed with location_start + offset.
    """
    numbered = []
    for offset, line in enumerate(window["lines"]):
        absolute_line_number = window["location_start"] + offset
        numbered.append(f"{absolute_line_number}: {line}")
    return "".join(numbered)


def _capped_chunk_text(chunk_text: str, cap: int = CHUNK_TEXT_CAP) -> str:
    """Head-keep truncation with an honest marker when the reconstruction exceeds cap."""
    if len(chunk_text) <= cap:
        return chunk_text
    return (
        chunk_text[:cap]
        + f"\n\n[TRUNCATED: showing the first {cap:,} of {len(chunk_text):,} characters of the "
        "reconstruction -- the tail was cut to fit the model's input limit; the moment under "
        "judgment falls early in the session]"
    )


