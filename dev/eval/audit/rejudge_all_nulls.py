def _strip_fences(result_text: str) -> str:
    json_text = result_text
    if "```json" in json_text:
        json_text = json_text.split("```json")[1].split("```")[0]
    elif "```" in json_text:
        json_text = json_text.split("```")[1].split("```")[0]
    return json_text.strip()


def _parse_response(
    result_text: str, ask_fields: List[str]
) -> Tuple[bool, Optional[Dict[str, Dict[str, Any]]]]:
    """
    Parse and validate the model's response.

    Returns (ok, fields). ok=False means the response was malformed/invalid
    (bad JSON, wrong key set, out-of-enum value -- including null -- or
    missing/empty rationale) and the caller should retry once, then skip.
    """
    try:
        parsed = json.loads(_strip_fences(result_text))
    except json.JSONDecodeError:
        return False, None

    if not isinstance(parsed, dict) or set(parsed.keys()) != set(ask_fields):
        return False, None

    fields: Dict[str, Dict[str, Any]] = {}
    for field in ask_fields:
        entry = parsed[field]
        if not isinstance(entry, dict):
            return False, None
        value = entry.get("value")
        if not any(value is valid for valid in (True, False)) and value != "not_applicable":
            return False, None
        rationale = entry.get("rationale")
        if not isinstance(rationale, str) or not rationale.strip():
            return False, None
        fields[field] = {"value": value, "rationale": rationale.strip()}
    return True, fields


