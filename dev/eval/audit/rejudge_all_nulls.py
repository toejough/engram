def _load_moments() -> List[Dict[str, Any]]:
    moments: List[Dict[str, Any]] = []
    with open(MOMENTS_PATH, "r") as f:
        for line in f:
            line = line.strip()
            if line:
                moments.append(json.loads(line))
    return moments


def _null_fields_for(moment: Dict[str, Any]) -> List[str]:
    """The LLM-judged null fields this moment needs asked, in FIELD_ORDER."""
    finding = moment.get("finding_side") or {}
    writing = moment.get("writing_side") or {}
    fields: List[str] = []
    if (
        finding.get("search_targeted_right_thing") is None
        and finding.get("memory_existed") is True
        and finding.get("search_ran") not in (None, "none")
    ):
        fields.append("search_targeted_right_thing")
    if finding.get("outdated_outranked_replacement") is None and finding.get("surfaced") is True:
        fields.append("outdated_outranked_replacement")
    if writing.get("strength_mismatch_flagged") is None and finding.get("surfaced") is True:
        fields.append("strength_mismatch_flagged")
    if writing.get("note_well_targeted") is None and writing.get("note_written") is True:
        fields.append("note_well_targeted")
    if writing.get("note_not_duplicate") is None and writing.get("note_written") is True:
        fields.append("note_not_duplicate")
    if writing.get("note_superseded_correctly") is None and writing.get("note_written") is True:
        fields.append("note_superseded_correctly")
    if writing.get("worth_learning_from") is None:
        fields.append("worth_learning_from")
    return fields


def _load_targets() -> List[Dict[str, Any]]:
    """
    Union all populations into ONE list of target moments (moments.jsonl
    order), each annotated with ask_fields (may be empty for the recheck-only
    moment) and needs_existence_recheck.
    """
    targets: List[Dict[str, Any]] = []
    for moment in _load_moments():
        ask_fields = _null_fields_for(moment)
        needs_recheck = (moment.get("finding_side") or {}).get("memory_existed") is None
        if not ask_fields and not needs_recheck:
            continue
        targets.append(
            {
                "moment": moment,
                "ask_fields": ask_fields,
                "needs_existence_recheck": needs_recheck,
            }
        )
    return targets


