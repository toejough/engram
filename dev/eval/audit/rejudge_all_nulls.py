def _load_done_ids(path: Path) -> List[str]:
    """moment_ids already written to the output file (for resume)."""
    if not path.exists():
        return []
    done: List[str] = []
    with open(path, "r") as f:
        for line in f:
            line = line.strip()
            if line:
                done.append(json.loads(line)["moment_id"])
    return done


def _print_final_summary(targets: List[Dict[str, Any]]) -> None:
    """Read the whole output file back and print the run-wide summary."""
    records = []
    with open(OUTPUT_PATH, "r") as f:
        for line in f:
            line = line.strip()
            if line:
                records.append(json.loads(line))

    judged = [r for r in records if r["skipped_reason"] is None]
    skipped = [r for r in records if r["skipped_reason"] is not None]
    total_cost = sum(r["cost_usd"] for r in records if r["cost_usd"] is not None)

    print()
    print("=== FINAL SUMMARY ===")
    print(f"Targets: {len(records)}/{len(targets)} recorded in {OUTPUT_PATH.name}")
    print(f"Judged: {len(judged)}; skipped: {len(skipped)}")
    for reason, count in sorted(Counter(r["skipped_reason"] for r in skipped).items()):
        print(f"  skipped ({reason}): {count}")
    print("per-field value tallies (judged targets):")
    for field in FIELD_ORDER:
        tally = Counter(
            str(r["fields"][field]["value"]) for r in judged if field in r.get("fields", {})
        )
        if tally:
            rendered = ", ".join(f"{value}: {count}" for value, count in sorted(tally.items()))
            print(f"  {field}: {rendered}")
    rechecks = [r for r in records if r.get("memory_existed_recheck") is not None]
    if rechecks:
        print("memory_existed rechecks:")
        for r in rechecks:
            print(f"  {r['moment_id']}: {json.dumps(r['memory_existed_recheck'])}")
    print(
        f"Total real $ cost: ${total_cost:.4f} (sum of per-target cost_usd -- each the "
        "total_cost_usd claude -p's own --output-format json response reported for that "
        "target's real call(s), across ALL invocations of this script; not an estimate)"
    )


def main() -> None:
    max_seconds = float(sys.argv[1]) if len(sys.argv) > 1 else None
    started = time.monotonic()

    targets = _load_targets()
    prep = _preflight(targets)

    done_ids = set(_load_done_ids(OUTPUT_PATH))

    # ONE shared cfg_dir (real keychain-seeded creds) reused across all calls.
    cfg_dir = tempfile.mkdtemp(prefix="rejudge-all-nulls-cfg-")
    _build_cfg_dir(cfg_dir)

    # Cache windows / chunk reconstructions per transcript: several targets
    # share a transcript, and both are deterministic pure reads.
    windows_cache: Dict[str, List[Dict[str, Any]]] = {}
    reconstruction_cache: Dict[str, str] = {}

    invocation_spend = 0.0

    try:
        with open(OUTPUT_PATH, "a") as out_f:

            def emit(record: Dict[str, Any]) -> None:
                out_f.write(json.dumps(record) + "\n")
                out_f.flush()
                done_ids.add(record["moment_id"])

            for index, target in enumerate(targets, start=1):
                moment = target["moment"]
                moment_id = moment["moment_id"]
                target_prep = prep[moment_id]
                ask_fields = target["ask_fields"]
                skeleton = {
                    "moment_id": moment_id,
                    "fields": {},
                    "judged_from": target_prep["judged_from"],
                    "memory_existed_recheck": None,
                    "skipped_reason": None,
                    "cost_usd": None,
                }

                if moment_id in done_ids:
                    continue  # resume: already recorded by a prior invocation

                if max_seconds is not None and time.monotonic() - started > max_seconds:
                    print(
                        f"time budget ({max_seconds:.0f}s) reached; stopping between targets",
                        flush=True,
                    )
                    break

                print(
                    f"[{index}/{len(targets)}] judging {moment_id} "
                    f"(judged_from={target_prep['judged_from']}, fields={ask_fields}, "
                    f"recheck={target['needs_existence_recheck']}) ...",
                    flush=True,
                )

                target_cost = 0.0
                try:
                    outcome = dict(skeleton)
                    transcript_path = moment["transcript_path"]
                    location = moment["location"]

                    # -------- LLM judgment over this moment's null fields --------
                    if ask_fields:
                        if target_prep["judged_from"] == "chunks":
                            if transcript_path not in reconstruction_cache:
                                reconstruction_cache[transcript_path] = _reconstruct_from_chunks(
                                    _find_chunk_file(transcript_path)
                                )
                            context_intro = (
                                "The original transcript file was deleted by session retention. "
                                "The record below is reconstructed from engram's chunk index -- "
                                "stripped conversational turns, tool-call detail reduced, the "
                                "original line numbering is unavailable. It is the surviving "
                                "conversational record for this session, in turn order.\n\n"
                                "RECONSTRUCTED TRANSCRIPT (from engram's chunk index):"
                            )
                            context_body = _capped_chunk_text(
                                reconstruction_cache[transcript_path]
                            )
                            location_note = (
                                f"- approximate original location: line {location} of the original "
                                "transcript JSONL (that numbering does not map onto the "
                                "reconstruction above; use the description to find the moment)"
                            )
                            prompt = _build_prompt(
                                context_intro,
                                context_body,
                                target_prep["extra_blocks"],
                                location_note,
                                moment["moment_type"],
                                moment["description"],
                                ask_fields,
                                target_prep["injected"],
                            )
                        else:
                            if transcript_path not in windows_cache:
                                windows_cache[transcript_path] = split_into_windows(transcript_path)
                            window = _find_covering_window(
                                windows_cache[transcript_path], location
                            )
                            if window is None:
                                emit({**skeleton, "skipped_reason": SKIP_NO_WINDOW})
                                print(
                                    f"  skipped: {SKIP_NO_WINDOW} (location {location})",
                                    flush=True,
                                )
                                continue
                            context_intro = (
                                f"WINDOW (lines {window['location_start']}-"
                                f"{window['location_end']}; each line is prefixed with its "
                                "absolute line number):"
                            )
                            prompt = _build_prompt(
                                context_intro,
                                _numbered_window_text(window),
                                target_prep["extra_blocks"],
                                f"- location: line {location}",
                                moment["moment_type"],
                                moment["description"],
                                ask_fields,
                                target_prep["injected"],
                            )

                        # First attempt + ONE retry on a malformed/invalid response.
                        judged_fields: Optional[Dict[str, Dict[str, Any]]] = None
                        deterministic_skip: Optional[str] = None
                        for attempt in (1, 2):
                            response = _run_claude_p(prompt, "sonnet", cfg_dir=cfg_dir)
                            call_cost = response.get("total_cost_usd", 0) or 0
                            target_cost += call_cost
                            invocation_spend += call_cost

                            if response.get("prompt_too_long"):
                                # Deterministic rejection -- never retried.
                                deterministic_skip = SKIP_TOO_LONG
                                break

                            if response.get("exhausted_retries"):
                                # HALT THE ENTIRE RUN: a sustained auth/API outage
                                # must never be absorbed as per-moment skips
                                # (2026-09-02 lesson). Output so far is recorded;
                                # re-running resumes from here.
                                raise ExhaustedRetriesError(
                                    f"claude -p exhausted retries on {moment_id} -- halting "
                                    f"the entire run (${invocation_spend:.4f} spent this "
                                    "invocation; output so far is recorded; re-run to resume)"
                                )

                            ok, fields = _parse_response(response.get("result", ""), ask_fields)
                            if ok:
                                judged_fields = fields
                                break
                            if attempt == 1:
                                print("  malformed/invalid response; retrying once ...", flush=True)

                        if deterministic_skip is not None:
                            outcome["skipped_reason"] = deterministic_skip
                        elif judged_fields is None:
                            outcome["skipped_reason"] = SKIP_UNPARSEABLE
                        else:
                            outcome["fields"] = judged_fields

                    # -------- REAL existence-check rerun (population f) --------
                    if target["needs_existence_recheck"]:
                        try:
                            if transcript_path not in reconstruction_cache:
                                reconstruction_cache[transcript_path] = _reconstruct_from_chunks(
                                    _find_chunk_file(transcript_path)
                                )
                            phrases, phrase_spend, phrase_failure = _generate_search_phrases(
                                moment, reconstruction_cache[transcript_path], cfg_dir
                            )
                            target_cost += phrase_spend
                            invocation_spend += phrase_spend
                            if phrases is None:
                                outcome["memory_existed_recheck"] = {
                                    "existence_recheck_failed_reason": phrase_failure,
                                    "phrase_gen_cost_usd": phrase_spend,
                                }
                            else:
                                timestamp = moment.get("timestamp")
                                if not timestamp:
                                    outcome["memory_existed_recheck"] = {
                                        "existence_recheck_failed_reason": (
                                            "moment has no timestamp -- point-in-time check "
                                            "impossible"
                                        ),
                                        "phrase_gen_cost_usd": phrase_spend,
                                    }
                                else:
                                    recheck = _existence_recheck(timestamp, phrases)
                                    recheck["phrase_gen_cost_usd"] = phrase_spend
                                    outcome["memory_existed_recheck"] = recheck
                        except ExhaustedRetriesError:
                            raise
                        except Exception as recheck_error:  # noqa: BLE001 -- recorded, never fabricated
                            outcome["memory_existed_recheck"] = {
                                "existence_recheck_failed_reason": (
                                    f"{type(recheck_error).__name__}: {recheck_error}"
                                )
                            }

                    outcome["cost_usd"] = target_cost if target_cost > 0 else None
                    emit(outcome)
                    if outcome["skipped_reason"] is None:
                        rendered = {
                            field: entry["value"] for field, entry in outcome["fields"].items()
                        }
                        recheck_note = ""
                        if outcome["memory_existed_recheck"] is not None:
                            recheck_note = (
                                f" recheck={json.dumps(outcome['memory_existed_recheck'])}"
                            )
                        print(
                            f"  -> {rendered}{recheck_note} (${target_cost:.4f}; invocation "
                            f"spend so far ${invocation_spend:.4f})",
                            flush=True,
                        )
                    else:
                        print(f"  skipped: {outcome['skipped_reason']}", flush=True)

                except ExhaustedRetriesError:
                    raise  # halt the run -- never absorbed as a per-moment skip
                except Exception as moment_error:  # noqa: BLE001 -- one bad moment must not kill the sweep
                    emit(
                        {
                            **skeleton,
                            "skipped_reason": (
                                f"error: {type(moment_error).__name__}: {moment_error}"
                            ),
                            "cost_usd": target_cost if target_cost > 0 else None,
                        }
                    )
                    print(
                        f"  skipped (error): {type(moment_error).__name__}: {moment_error}",
                        flush=True,
                    )
    finally:
        shutil.rmtree(cfg_dir, ignore_errors=True)

    if len(done_ids) >= len(targets):
        _print_final_summary(targets)
    else:
        print(
            f"\nIncomplete: {len(done_ids)}/{len(targets)} targets recorded "
            f"(${invocation_spend:.4f} spent this invocation). Re-run to resume.",
            flush=True,
        )


if __name__ == "__main__":
    main()
