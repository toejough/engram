def _response_format_block(ask_fields: List[str]) -> str:
    example = ", ".join(
        f'"{field}": {{"value": true | false | "not_applicable", "rationale": "<one sentence>"}}'
        for field in ask_fields
    )
    return f"{RESPONSE_FORMAT_HEADER}\n{{{example}}}\n{RESPONSE_FORMAT_FOOTER}"


def _build_prompt(
    context_intro: str,
    context_body: str,
    extra_blocks: List[Tuple[str, str]],
    location_note: str,
    moment_type: str,
    description: str,
    ask_fields: List[str],
    injected: bool,
) -> str:
    parts = [
        "You are auditing one moment from a real agent-session transcript for a memory-loop audit.",
        "",
        context_intro,
        context_body,
    ]
    for label, body in extra_blocks:
        parts.extend(["", f"{label}:", body])
    parts.extend(
        [
            "",
            "MOMENT UNDER JUDGMENT:",
            location_note,
            f"- moment_type: {moment_type}",
            f"- description: {description}",
            "",
            _questions_block(ask_fields, injected),
            "",
            _response_format_block(ask_fields),
        ]
    )
    return "\n".join(parts)


